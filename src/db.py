"""Database connection factory (Phase 8, E3). No ORM.

`TARIFF_DB_URL` (postgresql://...) selects Postgres; otherwise the SQLite file
named by `TARIFF_DB_PATH` (default data/tariffs.db) is used, exactly as before.
A Postgres connection is wrapped so the stages keep their SQL and their shape:
the wrapper absorbs the dialect differences listed in the Phase 8a audit.

Shim list (all in this module):
  1. placeholders `?` -> `%s` (and literal `%` -> `%%`)
  2. `PRAGMA foreign_keys` -> no-op; `PRAGMA table_info(t)` -> emulated rows
  3. `BEGIN IMMEDIATE` -> transaction-scoped advisory lock (single writer)
  4. `sqlite_master` table listing -> information_schema view
  5. `cursor.lastrowid` -> `RETURNING id` on inserts into tables with an id column
  6. DDL types: INTEGER PRIMARY KEY -> identity, REAL/NUMERIC -> DOUBLE PRECISION
     (preserves SQLite's float storage exactly), DATE -> TEXT (dates are ISO strings)
  7. exceptions: `db.Error` covers sqlite3.Error and psycopg.Error
"""

import os
import re
import sqlite3
from pathlib import Path

try:
    import psycopg
except ImportError:  # SQLite-only environments keep working
    psycopg = None

Error = (sqlite3.Error,) + ((psycopg.Error,) if psycopg else ())

ADVISORY_LOCK_KEY = 8008
_POSTGRES_PREFIXES = ("postgresql://", "postgres://")


def is_postgres(target):
    return isinstance(target, str) and target.startswith(_POSTGRES_PREFIXES)


def default_target(default_path):
    """TARIFF_DB_URL wins, then TARIFF_DB_PATH, then the given default path."""
    url = os.environ.get("TARIFF_DB_URL")
    if url:
        return url
    return Path(os.environ.get("TARIFF_DB_PATH") or default_path)


def describe(target):
    """Printable form of a target with any password removed."""
    if is_postgres(target):
        return re.sub(r"://([^:/@]+):[^@]*@", r"://\1:***@", target)
    return str(target)


def connect(target, readonly=False):
    if is_postgres(target):
        if psycopg is None:
            raise RuntimeError("psycopg is required for postgresql:// targets.")
        return PgConnection(target, readonly=readonly)
    if readonly:
        return sqlite3.connect(f"file:{Path(target)}?mode=ro", uri=True)
    return sqlite3.connect(Path(target))


# ---------------------------------------------------------------- translation
_PRAGMA_TABLE_INFO = re.compile(r'^\s*PRAGMA\s+table_info\(\s*"?(\w+)"?\s*\)\s*;?\s*$', re.I)
_PRAGMA_FK = re.compile(r"^\s*PRAGMA\s+foreign_keys", re.I)
_BEGIN = re.compile(r"^\s*BEGIN(\s+IMMEDIATE)?\s*;?\s*$", re.I)
_INSERT = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.I)
_SQLITE_MASTER = (
    "(SELECT table_name AS name, 'table' AS type FROM information_schema.tables "
    "WHERE table_schema = current_schema() AND table_type = 'BASE TABLE') AS sqlite_master"
)

_TABLE_INFO_SQL = """
SELECT c.ordinal_position - 1, c.column_name, c.data_type,
       CASE WHEN c.is_nullable = 'NO' THEN 1 ELSE 0 END, c.column_default,
       COALESCE((
           SELECT k.ordinal_position
           FROM information_schema.table_constraints t
           JOIN information_schema.key_column_usage k
             ON k.constraint_name = t.constraint_name
            AND k.table_schema = t.table_schema AND k.table_name = t.table_name
           WHERE t.constraint_type = 'PRIMARY KEY'
             AND t.table_schema = c.table_schema AND t.table_name = c.table_name
             AND k.column_name = c.column_name
       ), 0)
FROM information_schema.columns c
WHERE c.table_schema = current_schema() AND c.table_name = %s
ORDER BY c.ordinal_position
"""


def translate_ddl(sql):
    sql = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\b",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        sql,
        flags=re.I,
    )
    sql = re.sub(r"\b(REAL|NUMERIC)\b", "DOUBLE PRECISION", sql, flags=re.I)
    return re.sub(r"\bDATE\b", "TEXT", sql, flags=re.I)


def translate(sql):
    """Return the Postgres form of a SQLite statement."""
    head = sql.lstrip()[:12].upper()
    if head.startswith(("CREATE TABLE", "ALTER TABLE")):
        sql = translate_ddl(sql)
    sql = re.sub(r"\bsqlite_master\b", _SQLITE_MASTER, sql)
    return sql.replace("%", "%%").replace("?", "%s")


# --------------------------------------------------------------- Pg wrapper
class PgCursor:
    def __init__(self, connection):
        self._connection = connection
        self._cursor = connection._raw.cursor()
        self.lastrowid = None
        self._rows = None

    def execute(self, sql, params=()):
        connection = self._connection
        self.lastrowid = None
        self._rows = None
        if _PRAGMA_FK.match(sql):
            self._rows = []
            return self
        if _BEGIN.match(sql):
            self._cursor.execute("SELECT pg_advisory_xact_lock(%s)", (ADVISORY_LOCK_KEY,))
            self._rows = []
            return self
        match = _PRAGMA_TABLE_INFO.match(sql)
        if match:
            self._cursor.execute(_TABLE_INFO_SQL, (match.group(1),))
            self._rows = self._cursor.fetchall()
            return self
        translated = translate(sql)
        insert = _INSERT.match(sql)
        if insert and "RETURNING" not in sql.upper() and connection._has_id(insert.group(1)):
            self._cursor.execute(translated.rstrip().rstrip(";") + " RETURNING id", params)
            self.lastrowid = self._cursor.fetchone()[0]
            self._rows = []
            return self
        self._cursor.execute(translated, params)
        return self

    def executemany(self, sql, seq):
        self._cursor.executemany(translate(sql), seq)
        return self

    @property
    def rowcount(self):
        return self._cursor.rowcount

    @property
    def description(self):
        return self._cursor.description

    def fetchone(self):
        if self._rows is not None:
            return self._rows.pop(0) if self._rows else None
        return self._cursor.fetchone()

    def fetchall(self):
        if self._rows is not None:
            rows, self._rows = self._rows, []
            return rows
        return self._cursor.fetchall()

    def fetchmany(self, size=1):
        if self._rows is not None:
            rows, self._rows = self._rows[:size], self._rows[size:]
            return rows
        return self._cursor.fetchmany(size)

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        self._cursor.close()


class PgConnection:
    def __init__(self, url, readonly=False):
        # SQL_ASCII databases (initdb --locale=C without an encoding) would otherwise yield bytes
        self._raw = psycopg.connect(url, autocommit=False, client_encoding="UTF8")
        if readonly:
            self._raw.read_only = True
        self._id_tables = {}

    def _has_id(self, table):
        if table not in self._id_tables:
            with self._raw.cursor() as cursor:
                cursor.execute(
                    "SELECT 1 FROM information_schema.columns WHERE table_schema = "
                    "current_schema() AND table_name = %s AND column_name = 'id'",
                    (table,),
                )
                self._id_tables[table] = cursor.fetchone() is not None
        return self._id_tables[table]

    def cursor(self):
        return PgCursor(self)

    def execute(self, sql, params=()):
        return self.cursor().execute(sql, params)

    def executemany(self, sql, seq):
        return self.cursor().executemany(sql, seq)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        return False
